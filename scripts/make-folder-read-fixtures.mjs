#!/usr/bin/env node
/**
 * Writes test/fixtures/folder-read.json (inputs + the JS reader's output) and the Swift copy
 * apple/Stello/StelloTests/FolderReadFixtures.swift, so the web reader (src/lib/folder-read.js)
 * and the Mac one (Store/FolderReader.swift) are checked against the same expected results.
 * Run after changing either reader:
 *   node scripts/make-folder-read-fixtures.mjs
 * Review the diff of the JSON before committing: it is the expected output.
 */
import { writeFileSync } from 'node:fs';
import { itemFile } from '../src/lib/folder-write.js';
import { fileEdits, itemFromFile } from '../src/lib/folder-read.js';

const ID = '4c9f1824-45ad-4265-98a6-95b71f16338b';
const item = {
  id: ID, slug: 'kometa-fonts', title: 'Future-facing fonts', source_url: 'https://kometa.xyz/',
  kind: 'typeface', domain: 'kometa.xyz', author: 'Kometa', summary: 'Fonts with a “future” feel.',
  status: 'active', added_at: '2026-11-28T07:00:00.000Z', analyzed_at: '2026-11-28T07:01:00.000Z',
  needs_review: false, enrichment_status: 'done', open_count: 2, cover_aspect: 1.5,
  metadata: { typeDesigner: 'Jane Doe', price: '10' },
  tags: [{ tag: 'serif', category: 'style', weight: 0.9, source: 'ai' }, { tag: 'germany', category: 'location', weight: 1, source: 'ai' }, { tag: 'blue', category: 'color', weight: 0.6 }],
  images: [{ path: '/img/u/a.webp', is_primary: true, source: 'og', width: 1200, height: 800 }],
  snippets: [{ text: 'A quote', source: 'page', added_at: '2026-11-28T07:00:00.000Z' }],
  body_markdown: 'My note about it.',
};
const entities = [
  { id: 'person-kometa', name: 'Kometa', kind: 'foundry', aliases: [], type: 'person', path: 'people/kometa.md' },
  { id: 'person-jane-doe', name: 'Jane Doe', kind: 'individual', aliases: [], type: 'person', path: 'people/jane-doe.md' },
  { id: 'place-germany', name: 'Germany', kind: 'country', aliases: [], type: 'place', path: 'places/germany.md' },
  { id: 'place-south-korea', name: 'South Korea', kind: 'country', aliases: [], type: 'place', path: 'places/south-korea.md' },
];
const path = 'items/2026/11/kometa-fonts.md';
const file = itemFile(item, { entities, paths: new Set(), existing: null }).text;
const edit = (fn) => fn(file);
const line = (text, key, value) => text.replace(new RegExp(`^${key}: .*$`, 'm'), value === undefined ? '' : `${key}: ${JSON.stringify(value)}`).replace(/\n\n(?=[a-z_]+:)/g, '\n');

const edits = [];
const addEdit = (name, text, it = item) => edits.push({ name, item: it, path, entities, text, expect: fileEdits(it, text, { path, entities }) });
addEdit('the file Stello wrote: nothing changed', file);
addEdit('title changed', line(file, 'title', 'Kometa: future fonts'));
addEdit('summary removed', line(file, 'summary'));
addEdit('marked for review, kind changed', line(line(file, 'kind', 'website'), 'status', 'active').replace(/^tags:/m, 'review: true\ntags:'));
addEdit('a tag added and a weight changed', file.replace('  style: {"serif":0.9}', '  style: {"serif":0.5,"display":1}'));
addEdit('a place swapped', file.replace('["place-germany"]', '["place-south-korea"]'));
addEdit('note rewritten', file.replace('My note about it.', 'A longer note, written in a text editor.\n\nWith two paragraphs.'));
addEdit('meta edited: people kept', file.replace(/^meta: .*$/m, 'meta: {"price":"12","weights":"9"}'));
addEdit('an image line removed', file.replace(/^images:\n  - .*\n/m, '').replace(/^cover: .*\n/m, ''));
addEdit('file of another item: nothing', file.replace(ID, '11111111-2222-4333-8444-555555555555'));
addEdit('renamed only (same text): nothing', file);

const fresh = [];
const addFresh = (name, text, p, modified) => fresh.push({ name, text, path: p, entities, modified, expect: itemFromFile(text, p, { entities, modified }) });
addFresh('a Stello file Stello did not have', file, 'items/2026/11/kometa-fonts.md', 1795867200000);
addFresh('a hand-written file with only an id and a title', '---\nid: "aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee"\ntitle: "Typed by hand"\n---\nSome words.\n', 'Notes/Typed by hand.md', 1795867200000);
addFresh('a people file is not an item', '---\nid: "person-kometa"\nname: "Kometa"\nkind: "foundry"\n---\n', 'people/kometa.md', 1795867200000);

writeFileSync(new URL('../test/fixtures/folder-read.json', import.meta.url), JSON.stringify({ edits, fresh }, null, 2) + '\n');
const json = JSON.stringify({ edits, fresh });
const swift = `// Generated by scripts/make-folder-read-fixtures.mjs from test/fixtures/folder-read.json. Don't edit.
// The web reader's expected output; FolderReaderTests checks FolderReader.swift gives the same.
enum FolderReadFixtures {
    static let json = #"""
${json}
"""#
}
`;
writeFileSync(new URL('../apple/Stello/StelloTests/FolderReadFixtures.swift', import.meta.url), swift);
console.log(`${edits.length} edit cases, ${fresh.length} new-item cases`);
